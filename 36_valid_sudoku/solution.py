class Solution(object):
    def isValidSudoku(self, board):
        """
        :type board: List[List[str]]
        :rtype: bool
        """
        for i in range(9):
            row_set = set()
            col_set = set()
            for j in range(9):

                if board[i][j] != '.':
                    if board[i][j] in row_set:
                        return False
                    row_set.add(board[i][j])

                if board[j][i] != '.':
                    if board[j][i] in col_set:
                        return False
                    col_set.add(board[j][i])

                if i % 3 == 0 and j % 3 == 0:
                    sqaure_set = set()
                    for s1 in range(i, i + 3):
                        for s2 in range(j, j + 3):
                            if board[s1][s2] != '.':
                                if board[s1][s2] in sqaure_set:
                                    return False
                                sqaure_set.add(board[s1][s2])
        return True

